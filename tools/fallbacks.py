"""工具的降级兜底(fallback)。

单独成文件的原因:同一段兜底逻辑原来在 main.py(手写版)和 graph/tool_adapters.py
(图版)各抄了一份,M5.3 的 MCP server 会成为第三份。三份文案迟早会漂。

**为什么兜底文案属于"工具"而不属于"调用方"**:
"请勿编造数字" 这句话是**对模型的约束**,而这个约束之所以必要,是因为
行情工具的失败模式是"拿不到数字"。只有工具自己知道它失败时该怎么向模型交代。
这也是 M5.3 里决定把可靠性层放在 server 侧的依据。
"""


def stock_fallback(symbol: str = "", days: int = 30) -> dict:
    """行情工具的兜底:明确告知不可用,并**显式禁止模型编造**。

    注意返回的不是空值也不是异常,而是一段模型能读懂的说明。
    降级的目标是让 Agent 继续走下去,而不是崩掉或者胡编。
    """
    return {"symbol": symbol, "error": "行情数据暂时不可用,请勿编造数字。"}
